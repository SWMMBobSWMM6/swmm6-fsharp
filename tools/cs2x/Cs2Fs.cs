    /// <summary>A member or type name as F# source spells it: keywords in double backticks.</summary>
    static string Fs(string n)
    {
        n = n.TrimStart('@');
        if (n.Contains('<') || n.Contains('>')) n = n.Replace("<", "_").Replace(">", "_");
        return FsKeywords.Contains(n) ? "``" + n + "``" : n;
    }

    static bool IsRuntime(ISymbol s)
    {
        var ns = s is INamespaceSymbol nss ? nss : s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace)
        {
            if (ns.Name == "Cpp" && ns.ContainingNamespace.IsGlobalNamespace) return true;
            ns = ns.ContainingNamespace;
        }
        return false;
    }

    static bool IsSystem(ISymbol s)
    {
        var ns = s is INamespaceSymbol nss ? nss : s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace) { if (ns.Name == "System" && ns.ContainingNamespace.IsGlobalNamespace) return true; ns = ns.ContainingNamespace; }
        return false;
    }

    static readonly Dictionary<ISymbol, string> typeNames = new(SymbolEqualityComparer.Default);

    /// <summary>The F# name of an engine type: its namespace below openswmm and its class nesting, joined by _ (as
    /// the Java and Kotlin ports name them); the free functions of a namespace (C#'s static class _F) are F_ns.</summary>
    static string TypeIdent(INamedTypeSymbol t)
    {
        t = t.OriginalDefinition;
        if (typeNames.TryGetValue(t, out var n)) return n;
        var parts = new List<string>();
        for (var c = t; c != null; c = c.ContainingType) parts.Insert(0, c.Name);
        var ns = new List<string>();
        for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) ns.Insert(0, x.Name);
        if (ns.Count > 0 && (ns[0] == "openswmm" || ns[0] == "_global" || ns[0] == "Gen")) ns.RemoveAt(0);
        var s = string.Join("_", ns.Concat(parts));
        if (t.Name == "_F" && t.ContainingType == null)
        {
            var full = new List<string>();
            for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) full.Insert(0, x.Name);
            s = full.Count == 1 && full[0] == "openswmm" ? "F_" : full.Count > 0 && full[0] == "openswmm" ? "F_" + string.Join("_", full.Skip(1)) : "F_" + string.Join("_", full);
        }
        if (FsKeywords.Contains(s) || FsShadow.Contains(s)) s += "_";
        typeNames[t] = s;
        return s;
    }

    /// <summary>A field's F# name; one that hides a field of a base class (an engine exception's msg beside the
    /// runtime CppException's) gets its class's name appended, as in the Kotlin port.</summary>
    static string FieldIdent(IFieldSymbol f)
    {
        if (IsRuntime(f) || IsSystem(f)) return Fs(f.Name);
        var n = f.Name.TrimStart('@');
        if (!f.IsStatic)
            for (var b = f.ContainingType.BaseType; b != null && !IsSystem(b); b = b.BaseType)
                if (b.GetMembers(f.Name).OfType<IFieldSymbol>().Any(x => !x.IsStatic)) { n = n + "_" + TypeIdent(f.ContainingType); break; }
        return Fs(n);
    }

    static readonly Dictionary<IMethodSymbol, string> methodNames = new(SymbolEqualityComparer.Default);

    /// <summary>An engine method's F# name: C#'s name, except that a non-virtual method which hides a method of the same
    /// signature in a base or derived engine class gets its class's name appended (F# would find both and could not
    /// choose; C#'s 'new' picks the most derived), as the Java and Kotlin ports do.</summary>
    static string MethodIdent(IMethodSymbol m)
    {
        m = m.OriginalDefinition;
        if (m.ReducedFrom != null) m = m.ReducedFrom;
        if (IsRuntime(m) || IsSystem(m)) return Fs(m.Name);
        if (m.OverriddenMethod != null) return MethodIdent(m.OverriddenMethod);
        if (methodNames.TryGetValue(m, out var n)) return n;
        var nm = m.Name.TrimStart('@');
        if (!m.IsStatic && !(m.IsVirtual || m.IsAbstract || m.IsOverride) && HidesOrIsHidden(m)) nm += "_" + TypeIdent(m.ContainingType);
        n = Fs(nm);
        methodNames[m] = n;
        return n;
    }

    static bool SameParams(IMethodSymbol a, IMethodSymbol b) =>
        a.Parameters.Length == b.Parameters.Length &&
        a.Parameters.Zip(b.Parameters).All(p => SymbolEqualityComparer.Default.Equals(p.First.Type, p.Second.Type) && p.First.RefKind == p.Second.RefKind);

    static bool HidesOrIsHidden(IMethodSymbol m)
    {
        var t = m.ContainingType;
        for (var b = t.BaseType; b != null && !IsSystem(b) && !IsRuntime(b); b = b.BaseType)
            if (b.GetMembers(m.Name).OfType<IMethodSymbol>().Any(x => x.MethodKind == MethodKind.Ordinary && !x.IsStatic && SameParams(x, m))) return true;
        foreach (var d in engineTypes)
            if (Derives(d, t) && d.GetMembers(m.Name).OfType<IMethodSymbol>().Any(x => x.MethodKind == MethodKind.Ordinary && !x.IsStatic && SameParams(x, m) && !IsOverrideOf(x, m)))
                return true;
        return false;
    }

    static bool IsOverrideOf(IMethodSymbol m, IMethodSymbol b)
    {
        for (var o = m.OverriddenMethod; o != null; o = o.OverriddenMethod) if (SymbolEqualityComparer.Default.Equals(o.OriginalDefinition, b.OriginalDefinition)) return true;
        return false;
    }

    static bool Derives(INamedTypeSymbol d, INamedTypeSymbol b)
    {
        for (var x = d.BaseType; x != null; x = x.BaseType) if (SymbolEqualityComparer.Default.Equals(x.OriginalDefinition, b.OriginalDefinition)) return true;
        return false;
    }

    /// <summary>A System type as a qualified name usable before a static member: System.Double, System.Math, ...</summary>
    static string SysName(INamedTypeSymbol t)
    {
        t = t.OriginalDefinition;
        var name = StripArity(t.MetadataName);
        for (var c = t.ContainingType; c != null; c = c.ContainingType) name = StripArity(c.MetadataName) + "." + name;
        return t.ContainingNamespace.ToDisplayString() + "." + name;
    }

    static string StripArity(string s) { var i = s.IndexOf('`'); return i < 0 ? s : s.Substring(0, i); }

    // ------------------------------------------------------------------------------------------------ types
    static readonly List<INamedTypeSymbol> engineTypes = new();
    static readonly HashSet<INamedTypeSymbol> engineSet = new(SymbolEqualityComparer.Default);

    static bool IsEngine(ITypeSymbol t) => t is INamedTypeSymbol n && engineSet.Contains(n.OriginalDefinition);

    static void CollectTypes(List<SyntaxTree> gen)
    {
        foreach (var t in gen)
        {
            foreach (var node in t.GetRoot().DescendantNodes())
            {
                if (node is not (BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)) continue;
                var s = (INamedTypeSymbol)M(node).GetDeclaredSymbol(node)!;
                if (IsRuntime(s)) continue;
                if (engineSet.Add(s)) engineTypes.Add(s);
            }
        }
    }

    /// <summary>The F# spelling of a C# type.</summary>
    static string T(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Boolean: return "bool";
            case SpecialType.System_SByte: return "sbyte";
            case SpecialType.System_Byte: return "byte";
            case SpecialType.System_Int16: return "int16";
            case SpecialType.System_UInt16: return "uint16";
            case SpecialType.System_Char: return "char";
            case SpecialType.System_Int32: return "int";
            case SpecialType.System_UInt32: return "uint32";
            case SpecialType.System_Int64: return "int64";
            case SpecialType.System_UInt64: return "uint64";
            case SpecialType.System_Single: return "float32";
            case SpecialType.System_Double: return "float";
            case SpecialType.System_String: return "string";
            case SpecialType.System_Object: return "obj";
            case SpecialType.System_Void: return "unit";
            case SpecialType.System_IntPtr: return "nativeint";
        }
        if (t is IArrayTypeSymbol at)
        {
            if (at.Rank != 1) Todo("multidimensional array");
            return TArg(at.ElementType) + "[]";
        }
        if (t is ITypeParameterSymbol tp) return "'" + tp.Name;
        if (t is IPointerTypeSymbol) return Todo("pointer type");
        if (t is INamedTypeSymbol n)
        {
            if (IsEngine(n)) return TypeIdent(n);
            string name;
            if (IsRuntime(n)) { name = RuntimeTypeName(n); }
            else if (IsSystem(n))
            {
                var full = n.OriginalDefinition.ContainingNamespace.ToDisplayString() + "." + StripArity(n.OriginalDefinition.MetadataName);
                for (var c = n.ContainingType; c != null; c = c.ContainingType) full = c.ContainingNamespace.ToDisplayString() + "." + c.Name + "." + n.Name;
                name = full;
                Use("type " + name);
            }
            else return Todo("type outside engine, runtime and System: " + n.ToDisplayString());
            if (n.TypeArguments.Length > 0) name += "<" + string.Join(", ", n.TypeArguments.Select(TArg)) + ">";
            return name;
        }
        return Todo("type " + t.ToDisplayString());
    }

    /// <summary>A type in a type-argument or array-element position (parenthesized where F# needs it).</summary>
    static string TArg(ITypeSymbol t) => T(t);

    static string RuntimeTypeName(INamedTypeSymbol n)
    {
        var parts = new List<string>();
        for (var c = n.OriginalDefinition; c != null; c = c.ContainingType) parts.Insert(0, Fs(c.Name));
        var name = "Cpp." + string.Join(".", parts);
        Use("type " + n.OriginalDefinition.ToDisplayString());
        return name;
    }

    /// <summary>The value C# gives a field or local nobody assigned: zero of its type, false, or null.</summary>
    static string DefaultOf(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Boolean: return "false";
            case SpecialType.System_SByte: return "0y";
            case SpecialType.System_Byte: return "0uy";
            case SpecialType.System_Int16: return "0s";
            case SpecialType.System_UInt16: return "0us";
            case SpecialType.System_Char: return "'\\000'";
            case SpecialType.System_Int32: return "0";
            case SpecialType.System_UInt32: return "0u";
            case SpecialType.System_Int64: return "0L";
            case SpecialType.System_UInt64: return "0UL";
            case SpecialType.System_Single: return "0.0f";
            case SpecialType.System_Double: return "0.0";
        }
        return "Unchecked.defaultof<" + T(t) + ">";
    }

    static bool IsPrimitiveNumeric(ITypeSymbol t) => t.SpecialType switch
    {
        SpecialType.System_SByte or SpecialType.System_Byte or SpecialType.System_Int16 or SpecialType.System_UInt16 or
        SpecialType.System_Char or SpecialType.System_Int32 or SpecialType.System_UInt32 or SpecialType.System_Int64 or
        SpecialType.System_UInt64 or SpecialType.System_Single or SpecialType.System_Double => true,
        _ => false
    };

    /// <summary>The F# conversion function to a primitive type.</summary>
    static string ConvFn(ITypeSymbol t) => t.SpecialType switch
    {
        SpecialType.System_SByte => "sbyte", SpecialType.System_Byte => "byte", SpecialType.System_Int16 => "int16",
        SpecialType.System_UInt16 => "uint16", SpecialType.System_Char => "char", SpecialType.System_Int32 => "int",
        SpecialType.System_UInt32 => "uint32", SpecialType.System_Int64 => "int64", SpecialType.System_UInt64 => "uint64",
        SpecialType.System_Single => "float32", SpecialType.System_Double => "float",
        _ => Todo("conversion to " + t.ToDisplayString())
    };
}
