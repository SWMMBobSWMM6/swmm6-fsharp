// Cs2Fs - translate the generated C# SWMM6 engine (cs/gen, with the engine's hand-written partial classes
// cs/runtime/Hand_*.cs) into F#, using Roslyn's semantic model: one IOperation tree per method, built into a small
// statement tree, restructured (F# has no return, break, continue or goto) and printed as F#. The F# runtime
// (fsharp/runtime/*.fs) has the C# runtime's classes, members and signatures, so a runtime call is written as the
// C# engine writes it. The mapping is recorded in FS.md.
//
//   dotnet bin/cs2fs.dll CS_DIR FSHARP_GEN_DIR
//
// writes FSHARP_GEN_DIR/Engine.fs (namespace rec Engine), and beside FSHARP_GEN_DIR cs2fs_todo.txt (constructs not
// translated), cs2fs_runtime.txt (the runtime and System members the engine uses) and cs2fs_stats.txt (how the
// jumps were translated).
//
// Written by Claude (Anthropic) for Robert Dickinson's SWMM6 ports; see AI-USE.md and fsharp/README.md.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

public sealed class Todo : Exception { public Todo(string m) : base(m) { } }

public static partial class Cs2Fs
{
    static CSharpCompilation comp = null!;
    static readonly Dictionary<SyntaxTree, SemanticModel> models = new();
    static SemanticModel M(SyntaxNode n) => models[n.SyntaxTree];
    static readonly SortedDictionary<string, int> todos = new();
    static readonly SortedDictionary<string, int> manifest = new();   // runtime / System member used -> count
    static readonly SortedDictionary<string, long> stats = new();

    public static int Main(string[] args)
    {
        var cs = args[0];
        var outDir = args[1];
        var files = Directory.GetFiles(Path.Combine(cs, "gen"), "*.cs").Concat(Directory.GetFiles(Path.Combine(cs, "runtime"), "*.cs"))
            .Where(f => !f.EndsWith("Program.cs")).OrderBy(f => f, StringComparer.Ordinal).ToArray();
        var opts = new CSharpParseOptions(LanguageVersion.Latest);
        var trees = files.Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), opts, f)).ToList();
        var fw = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        var refs = new List<MetadataReference>();
        foreach (var f in Directory.GetFiles(fw, "*.dll"))
        {
            var b = Path.GetFileName(f);
            if (b.StartsWith("Microsoft.VisualBasic") || b == "mscorlib.dll") continue;
            try { refs.Add(MetadataReference.CreateFromFile(f)); } catch { }
        }
        comp = CSharpCompilation.Create("engine", trees, refs, new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errs = comp.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
        if (errs.Count > 0) { foreach (var e in errs.Take(10)) Console.Error.WriteLine(e); return 1; }
        foreach (var t in trees) models[t] = comp.GetSemanticModel(t);
        var gen = trees.Where(t => t.FilePath.Contains("/gen/") || Path.GetFileName(t.FilePath).StartsWith("Hand_")).ToList();

        Directory.CreateDirectory(outDir);
        CollectTypes(gen);
        foreach (var g in engineTypes.GroupBy(TypeIdent).Where(g => g.Count() > 1)) Note("two types named " + g.Key);
        Analyze(gen);
        var sb = new StringBuilder();
        sb.Append(FileHeader);
        foreach (var s in engineTypes)
        {
            var tb = new StringBuilder();
            try { TypeDecl(s, tb); }
            catch (Todo e) { tb.Clear(); tb.Append("// TODO type ").Append(TypeIdent(s)).Append(": ").Append(e.Message).Append('\n'); }
            sb.Append(tb);
        }
        StaticsAndInit(sb);
        File.WriteAllText(Path.Combine(outDir, "Engine.fs"), sb.ToString());
        var parent = Path.GetDirectoryName(Path.GetFullPath(outDir))!;
        using (var w = new StreamWriter(Path.Combine(parent, "cs2fs_todo.txt")))
            foreach (var kv in todos.OrderByDescending(kv => kv.Value).ThenBy(kv => kv.Key, StringComparer.Ordinal)) w.WriteLine("{0,6}  {1}", kv.Value, kv.Key);
        using (var w = new StreamWriter(Path.Combine(parent, "cs2fs_runtime.txt")))
            foreach (var kv in manifest) w.WriteLine("{0,6}  {1}", kv.Value, kv.Key);
        using (var w = new StreamWriter(Path.Combine(parent, "cs2fs_stats.txt")))
            foreach (var kv in stats) w.WriteLine("{0,8}  {1}", kv.Value, kv.Key);
        Console.WriteLine("wrote Engine.fs: " + engineTypes.Count + " types, " + todos.Count + " TODO kinds, " + todos.Values.Sum() + " TODO sites");
        return 0;
    }

    const string FileHeader =
        "// Code generated by tools/cs2x/Cs2Fs.cs from cs/gen (the C# translation of the OpenSWMM 6 engine, HydroCouple\n" +
        "// openswmm.engine swmm6_rel 88329d6, Apache-2.0). DO NOT EDIT: change the translator or the runtime instead.\n" +
        "// Written for Robert Dickinson's SWMM6 ports by Claude (Anthropic); see AI-USE.md and fsharp/README.md.\n" +
        "namespace rec Engine\n\n" +
        "#nowarn \"25\" \"26\" \"64\" \"1182\" \"3370\" \"20\" \"40\" \"3391\" \"864\" \"44\" \"57\" \"9\" \"51\" \"52\" \"3536\" \"3560\"\n\n";

    static void Note(string what) { todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1; }
    static void Stat(string what, long n = 1) { stats[what] = stats.TryGetValue(what, out var c) ? c + n : n; }
    static void Use(string what) { manifest[what] = manifest.TryGetValue(what, out var c) ? c + 1 : 1; }

    static string Todo(string what)
    {
        Note(what);
        throw new Todo(what);
    }

